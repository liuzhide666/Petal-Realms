from pathlib import Path
import json
from playwright.sync_api import sync_playwright

html=Path(__file__).resolve().parent.parent/'site/index.html'
results=[]
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True)
    for label,viewport in [('desktop',{'width':1280,'height':800}),('mobile',{'width':390,'height':844})]:
        ctx=browser.new_context(viewport=viewport,device_scale_factor=1)
        page=ctx.new_page()
        errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.set_content(html.read_text(),wait_until='domcontentloaded')
        results.append((label,'verified_email_signup_hint','验证' in page.locator('#authModeHint').inner_text()))
        page.locator('#tabRegister').click()
        results.append((label,'signup_action_present','邮箱验证' in page.locator('#authHeading').inner_text()))
        page.evaluate("document.getElementById('guestBtn').click()")
        page.wait_for_timeout(550)
        snapshot=page.evaluate('window.PetalRealmsInfo.snapshot()')
        results.append((label,'game_started',bool(snapshot and snapshot.get('level'))))
        page.evaluate("document.getElementById('bagBtn').click()")
        page.wait_for_timeout(120)
        results.append((label,'bag_has_filter',page.locator('#itemSearch').count()==1 and page.locator('#bagSort').count()==1))
        results.append((label,'bag_deck_slots',page.locator('[data-deck]').count()==2 and page.locator('[data-slot]').count()>=6))
        bag_n=page.locator('[data-equip]').count()
        Path('artifacts/qa').mkdir(parents=True,exist_ok=True)
        page.screenshot(path=f'artifacts/qa/v59_{label}_bag.png')
        page.locator('#itemSearch').fill('XxDefinitelyMissing999')
        results.append((label,'bag_search_hides',page.locator('[data-equip]:visible').count()==0))
        page.locator('#itemSearch').fill('')
        results.append((label,'bag_search_restores',page.locator('[data-equip]:visible').count()==bag_n))
        page.evaluate("document.getElementById('panelClose').click()")
        page.evaluate("document.getElementById('craftBtn').click()")
        page.wait_for_timeout(120)
        results.append((label,'craft_filters',page.locator('#craftReadyOnly').count()==1 and page.locator('#itemRarity').count()==1))
        page.screenshot(path=f'artifacts/qa/v59_{label}_craft.png')
        page.locator('#craftReadyOnly').check()
        results.append((label,'craft_filters_render_without_exception',page.locator('#inventoryFilterCount').count()==1))
        page.evaluate("document.getElementById('panelClose').click()")
        page.evaluate("document.getElementById('pauseBtn').click()")
        page.evaluate("document.getElementById('settingsFromPause').click()")
        results.append((label,'hitbox_toggle',page.locator('#hitboxToggle').count()==1))
        page.evaluate("document.getElementById('hitboxToggle').click()")
        results.append((label,'hitbox_toggle_still_available',page.locator('#hitboxToggle').count()==1 and '关闭' in page.locator('#hitboxToggle').inner_text()))
        results.append((label,'no_runtime_errors',not errors))
        if errors: print('Errors for',label,errors)
        ctx.close()
    browser.close()
print(json.dumps([{'viewport':v,'test':t,'passed':ok} for v,t,ok in results],ensure_ascii=False,indent=2))
print('PASSED',sum(ok for _,_,ok in results),'/',len(results))
if not all(ok for _,_,ok in results): raise SystemExit(1)
